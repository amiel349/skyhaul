// Generate TypeScript types from the contract schemas. Called by generate.py:
//   node gen_ts.mjs <web dir> <schemas dir> <out dir> <version>
// json-schema-to-typescript is a pinned devDependency of web/, so it is resolved from there.
//
// The generator works on a preprocessed copy of the schemas:
// - Primitive common definitions (Lat, Uuid, ...) lose their title, so fields inline as
//   `number` / `string` with their doc comment. Otherwise a $ref with a sibling description
//   produces numbered duplicates (Uuid1). Enums and objects keep their names.
// - The envelope payload is typed `Record<string, unknown>`; its real type comes from
//   `Message<T>` in index.ts.

import { createRequire } from "node:module";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const [webDir, schemasDir, outDir, version] = process.argv.slice(2);
if (!version) {
  console.error("usage: gen_ts.mjs <web dir> <schemas dir> <out dir> <version>");
  process.exit(2);
}
const require = createRequire(path.join(path.resolve(webDir), "package.json"));
const { compileFromFile } = require("json-schema-to-typescript");

const BANNER = `// Generated by \`make contracts\` from contracts/schemas/${version}. Do not edit.`;
const GROUPS = ["commands", "telemetry"];

const readJson = (file) => JSON.parse(readFileSync(file, "utf8"));
const isNamed = (def) => Array.isArray(def.enum) || def.type === "object";

// Copy the schemas with the preprocessing described above.
const work = mkdtempSync(path.join(tmpdir(), "skyhaul-ts-"));
try {
  const common = readJson(path.join(schemasDir, "common.schema.json"));
  const named = new Set();
  for (const [key, def] of Object.entries(common.$defs)) {
    if (isNamed(def)) named.add(key);
    else delete def.title;
  }
  writeFileSync(path.join(work, "common.schema.json"), JSON.stringify(common));

  const envelope = readJson(path.join(schemasDir, "envelope.schema.json"));
  envelope.properties.payload.tsType = "Record<string, unknown>";
  writeFileSync(path.join(work, "envelope.schema.json"), JSON.stringify(envelope));

  const payloads = []; // [{group, name, title, type}]
  for (const group of GROUPS) {
    mkdirSync(path.join(work, group));
    for (const file of readdirSync(path.join(schemasDir, group)).sort()) {
      const schema = readJson(path.join(schemasDir, group, file));
      writeFileSync(path.join(work, group, file), JSON.stringify(schema));
      const name = file.replace(/\.schema\.json$/, "");
      payloads.push({ group, name, title: schema.title, type: name.toUpperCase() });
    }
  }

  const options = (extra) => ({
    bannerComment: BANNER,
    additionalProperties: false,
    strictIndexSignatures: true,
    format: true,
    ...extra,
  });

  // Names a schema pulls from common, so they can be imported instead of redeclared.
  const referencedNames = (file) => {
    const text = readFileSync(file, "utf8");
    const used = new Set();
    for (const m of text.matchAll(/common\.schema\.json#\/\$defs\/(\w+)/g)) {
      if (named.has(m[1])) used.add(m[1]);
    }
    return [...used].sort();
  };

  const emit = async (rel, compileOptions, importPrefix) => {
    const src = path.join(work, `${rel}.schema.json`);
    let ts = await compileFromFile(src, options({ cwd: path.dirname(src), ...compileOptions }));
    const imports = importPrefix === null ? [] : referencedNames(src);
    if (imports.length > 0) {
      ts = ts.replace(
        `${BANNER}\n`,
        `${BANNER}\n\nimport type { ${imports.join(", ")} } from "${importPrefix}common";\n`,
      );
    }
    const target = path.join(outDir, version, `${rel}.ts`);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, ts);
  };

  rmSync(outDir, { recursive: true, force: true });
  await emit("common", { unreachableDefinitions: true }, null);
  await emit("envelope", { declareExternallyReferenced: false }, "./");
  for (const p of payloads) {
    await emit(`${p.group}/${p.name}`, { declareExternallyReferenced: false }, "../");
  }

  // index.ts: re-export everything and add a discriminated Message union.
  const lines = [BANNER, ""];
  lines.push(`export type * from "./${version}/common";`);
  lines.push(`export type * from "./${version}/envelope";`);
  for (const p of payloads) lines.push(`export type * from "./${version}/${p.group}/${p.name}";`);
  lines.push("");
  lines.push(`import type { MessageType } from "./${version}/common";`);
  lines.push(`import type { Envelope } from "./${version}/envelope";`);
  for (const p of payloads) {
    lines.push(`import type { ${p.title} } from "./${version}/${p.group}/${p.name}";`);
  }
  lines.push("");
  lines.push("/** Payload type for each message type. */");
  lines.push("export interface PayloadByType {");
  for (const p of payloads) lines.push(`  ${p.type}: ${p.title};`);
  lines.push("}");
  lines.push("");
  lines.push("/** A decoded message of type T: the envelope with its typed payload. */");
  lines.push("export type Message<T extends MessageType = MessageType> = {");
  lines.push('  [K in T]: Omit<Envelope, "type" | "payload"> & { type: K; payload: PayloadByType[K] };');
  lines.push("}[T];");
  writeFileSync(path.join(outDir, "index.ts"), `${lines.join("\n")}\n`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
