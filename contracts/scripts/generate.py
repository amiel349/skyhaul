"""Generate Pydantic models and TypeScript types from the contract schemas.

    uv run python contracts/scripts/generate.py            # regenerate (make contracts)
    uv run python contracts/scripts/generate.py --check    # fail if committed output is stale

Generation always runs in a scratch directory with a pinned formatter config, so the output
does not depend on the caller's working directory or user-level ruff settings. In write mode
the result replaces the committed output; in check mode it is compared byte for byte.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
VERSIONS = ("v1",)
STALE_HINT = "Generated contracts are out of date: run make contracts"

PY_HEADER = "# Generated by `make contracts` from contracts/schemas/{version}. Do not edit."
# Settings for the formatter run on generated code. Pinned here so output is reproducible.
RUFF_TOML = 'line-length = 100\ntarget-version = "py312"\n'

DATAMODEL_FLAGS = (
    "--input-file-type=jsonschema",
    "--output-model-type=pydantic_v2.BaseModel",
    "--target-python-version=3.12",
    "--use-annotated",
    "--field-constraints",
    "--use-standard-collections",
    "--use-union-operator",
    "--use-type-alias",
    "--use-specialized-enum",
    "--use-title-as-name",
    "--use-double-quotes",
    "--disable-timestamp",
    "--formatters=ruff-format",
    "--base-class=skyhaul_contracts._base.ContractModel",
)


def py_out(root: Path, version: str) -> Path:
    return root / "contracts" / "src" / "skyhaul_contracts" / version / "_generated"


def ts_out(root: Path) -> Path:
    # One tree for all versions: ts/<version>/*.ts plus ts/index.ts for the current version.
    return root / "contracts" / "ts"


def generate_python(schemas: Path, version: str, scratch: Path) -> Path:
    work = scratch / "py"
    shutil.copytree(schemas, work / "in" / version)
    (work / "ruff.toml").write_text(RUFF_TOML)
    out = work / "out"
    env = {**os.environ, "RUFF_NO_CACHE": "true"}
    subprocess.run(  # noqa: S603 - fixed argv, no shell
        [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            f"--input={Path('in') / version}",
            f"--output={out}",
            f"--custom-file-header={PY_HEADER.format(version=version)}",
            *DATAMODEL_FLAGS,
        ],
        cwd=work,
        env=env,
        check=True,
    )
    return out


def generate_ts(schemas: Path, version: str, scratch: Path) -> Path:
    out = scratch / "ts"
    script = REPO / "contracts" / "scripts" / "gen_ts.mjs"
    subprocess.run(  # noqa: S603 - fixed argv, no shell
        ["node", str(script), str(REPO / "web"), str(schemas), str(out), version],  # noqa: S607
        check=True,
    )
    return out


def files(tree: Path) -> dict[str, bytes]:
    if not tree.exists():
        return {}
    return {
        p.relative_to(tree).as_posix(): p.read_bytes()
        for p in sorted(tree.rglob("*"))
        if p.is_file() and "__pycache__" not in p.parts
    }


def diff_trees(generated: Path, committed: Path, root: Path) -> list[str]:
    """Paths under ``committed`` that are missing, extra or different from ``generated``."""
    want, have = files(generated), files(committed)
    rel = committed.relative_to(root).as_posix()
    problems = [f"{rel}/{n} (missing)" for n in sorted(want.keys() - have.keys())]
    problems += [f"{rel}/{n} (not generated)" for n in sorted(have.keys() - want.keys())]
    common = sorted(want.keys() & have.keys())
    problems += [f"{rel}/{n} (changed)" for n in common if want[n] != have[n]]
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    parser.add_argument("--skip-ts", action="store_true", help="Python models only (no Node)")
    parser.add_argument(
        "--root", type=Path, default=REPO, help="repo root holding contracts/ (tests use a copy)"
    )
    args = parser.parse_args()
    root: Path = args.root.resolve()

    stale: list[str] = []
    for version in VERSIONS:
        schemas = root / "contracts" / "schemas" / version
        with tempfile.TemporaryDirectory(prefix="skyhaul-contracts-") as tmp:
            scratch = Path(tmp)
            outputs = [(generate_python(schemas, version, scratch), py_out(root, version))]
            # The UI only needs the newest version; older ones stay readable in Python only.
            if not args.skip_ts and version == VERSIONS[-1]:
                outputs.append((generate_ts(schemas, version, scratch), ts_out(root)))
            for generated, committed in outputs:
                if args.check:
                    stale += diff_trees(generated, committed, root)
                else:
                    shutil.rmtree(committed, ignore_errors=True)
                    shutil.copytree(generated, committed)

    if stale:
        print(STALE_HINT, file=sys.stderr)
        for line in stale:
            print(f"  {line}", file=sys.stderr)
        return 1
    if args.check:
        print("Generated contracts are up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
